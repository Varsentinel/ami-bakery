#!/usr/bin/env bash
# Writes the per-instance k3s settings that cannot be baked into the AMI.
#
# Runs on every boot, before k3s.service. Everything it emits lands in a
# config.yaml.d drop-in so the baked /etc/rancher/k3s/config.yaml stays
# untouched.
#
# Note that k3s only reads tls-san when it *issues* its certificates, i.e. on
# the first boot. If the instance's public IP later changes (a stop/start),
# this file is refreshed but the existing certificate is not: run
# `k3s certificate rotate` and restart k3s to pick the new SANs up.
set -euo pipefail

DROPIN_DIR=/etc/rancher/k3s/config.yaml.d
DROPIN="${DROPIN_DIR}/10-instance.yaml"

imds() {
  local path="$1" token
  token="$(curl -s --max-time 5 -X PUT "http://169.254.169.254/latest/api/token" \
    -H "X-aws-ec2-metadata-token-ttl-seconds: 60" || true)"
  [ -n "${token}" ] || return 0
  curl -s --max-time 5 -H "X-aws-ec2-metadata-token: ${token}" \
    "http://169.254.169.254/latest/meta-data/${path}" || true
}

mkdir -p "${DROPIN_DIR}"

sans=()
for key in local-ipv4 public-ipv4 local-hostname public-hostname; do
  value="$(imds "${key}")"
  # IMDS answers 404 with an HTML-ish body for absent keys (e.g. no public IP).
  case "${value}" in
    ""|*"<"*|*"not found"*|*"Not Found"*) continue ;;
  esac
  sans+=("${value}")
done

# Node name follows the hostname, which differs per instance; let k3s derive it.
{
  echo "# Generated by k3s-tls-san.service at first boot. Do not edit."
  if [ "${#sans[@]}" -gt 0 ]; then
    echo "tls-san:"
    printf '  - %s\n' "${sans[@]}"
  else
    echo "# IMDS unreachable: no extra TLS SANs added."
  fi
} > "${DROPIN}"

chmod 0600 "${DROPIN}"
echo "wrote ${DROPIN}:"
cat "${DROPIN}"
